// Builds rvitm-pages-index.js from data/pages/*.txt (output of scripts/crawl_site.js).
// Every page is split into heading-based sections ("chunks") so the chatbot can search
// and answer from ANY page on rvitm.edu.in.
//
// Usage: node scripts/build_page_index.js

const fs = require('fs');
const path = require('path');

const PAGES_DIR = path.join(__dirname, '..', 'data', 'pages');
const OUT_FILES = [
  path.join(__dirname, '..', 'rvitm-pages-index.js'),
  path.join(__dirname, '..', 'rvitm-chatbot', 'rvitm-pages-index.js')
];
const MAX_CHUNK = 900;   // chars per chunk
const MIN_CHUNK = 40;    // drop tiny fragments

function parsePage(raw) {
  const head = {};
  const lines = raw.split(/\r?\n/);
  let i = 0;
  for (; i < lines.length && lines[i].trim(); i++) {
    const m = lines[i].match(/^(URL|TITLE|DESCRIPTION):\s*(.*)$/);
    if (m) head[m[1].toLowerCase()] = m[2].trim();
  }
  const rest = lines.slice(i).join('\n');
  const [body, docsPart = ''] = rest.split(/\n--- DOCUMENTS ---\n/);
  const docs = docsPart.split('\n').map(l => l.trim()).filter(Boolean).map(l => {
    const k = l.lastIndexOf(' | ');
    return k > -1 ? { t: l.slice(0, k).trim() || 'Document', u: l.slice(k + 3).trim() } : null;
  }).filter(d => d && /^https?:/.test(d.u));
  return { url: head.url, title: head.title || '', desc: head.description || '', body: body || '', docs };
}

function cleanTitle(t) {
  return t.replace(/\s*[|–-]\s*(RVITM|RV Institute.*|Bengaluru|Bangalore)?\s*$/i, '').replace(/\s+-\s*$/, '').trim() || t;
}

(function main() {
  const files = fs.readdirSync(PAGES_DIR).filter(f => f.endsWith('.txt'));
  const pages = files.map(f => parsePage(fs.readFileSync(path.join(PAGES_DIR, f), 'utf8'))).filter(p => p.url);

  // ---- boilerplate removal: lines that repeat on many pages (menus, CTAs, FAQ shells) ----
  const lineFreq = new Map();
  for (const p of pages) {
    for (const l of new Set(p.body.split('\n').map(s => s.trim()).filter(Boolean))) {
      lineFreq.set(l, (lineFreq.get(l) || 0) + 1);
    }
  }
  const boilerThreshold = Math.max(4, Math.ceil(pages.length * 0.2));
  const isBoiler = l => (lineFreq.get(l) || 0) >= boilerThreshold ||
    /^(•|Learn More|Read More|View More|Know More|Apply Now|Click here|Download|Explore|Submit|Search|LPA|\+|%)$/i.test(l) ||
    /^[\d\s+%.,:\-–—•]*$/.test(l);

  const outPages = [];
  const chunks = [];
  const seenChunk = new Set();

  pages.sort((a, b) => a.url.localeCompare(b.url));
  for (const p of pages) {
    const pIdx = outPages.length;
    outPages.push({ u: p.url, t: cleanTitle(p.title), d: p.desc, docs: p.docs.slice(0, 25) });

    const lines = p.body.split('\n').map(s => s.trim()).filter(l => l && !isBoiler(l));
    let heading = cleanTitle(p.title);
    let buf = [];
    const flush = () => {
      let text = buf.join('\n').trim();
      buf = [];
      if (text.length < MIN_CHUNK) return;
      // split long sections into ~MAX_CHUNK pieces on line boundaries
      const parts = [];
      let cur = '';
      for (const l of text.split('\n')) {
        if ((cur + '\n' + l).length > MAX_CHUNK && cur) { parts.push(cur); cur = l; }
        else cur = cur ? cur + '\n' + l : l;
      }
      if (cur) parts.push(cur);
      for (const part of parts) {
        const key = part.toLowerCase().replace(/\W+/g, ' ').trim();
        if (part.length < MIN_CHUNK || seenChunk.has(key)) continue;
        seenChunk.add(key);
        chunks.push({ p: pIdx, h: heading, x: part });
      }
    };

    for (const l of lines) {
      if (l.startsWith('## ')) {
        const h = l.slice(3).trim();
        // Short heading lines start a new section; long "headings" are really content
        if (h.length <= 90) {
          if (buf.join(' ').length > 160) { flush(); heading = h; }
          else { if (!buf.length) heading = h; else buf.push(h); }
          continue;
        }
        buf.push(h);
        continue;
      }
      buf.push(l);
    }
    flush();

    // Make sure every page is findable even if its body was all boilerplate
    if (!chunks.some(c => c.p === pIdx)) {
      chunks.push({ p: pIdx, h: cleanTitle(p.title), x: (p.desc || cleanTitle(p.title)) });
    }
  }

  const payload = { generated: new Date().toISOString(), pages: outPages, chunks };
  const js =
`/**
 * RVITM WEBSITE PAGE INDEX — AUTO-GENERATED by scripts/build_page_index.js
 * Source: every crawled page of https://rvitm.edu.in/ (data/pages/*.txt)
 * Pages: ${outPages.length} | Sections: ${chunks.length} | Generated: ${payload.generated}
 * Do not edit by hand — re-run: node scripts/crawl_site.js && node scripts/build_page_index.js
 */
(function (root, data) {
  if (typeof module === 'object' && module.exports) module.exports = data;
  else root.RVITM_PAGES = data;
}(typeof self !== 'undefined' ? self : this, ${JSON.stringify(payload)}));
`;
  for (const f of OUT_FILES) fs.writeFileSync(f, js);
  console.log(`Pages: ${outPages.length}, sections: ${chunks.length}, boilerplate lines removed (>=${boilerThreshold} pages): ${[...lineFreq.values()].filter(v => v >= boilerThreshold).length}, size: ${(js.length / 1024).toFixed(0)} KB`);
})();
